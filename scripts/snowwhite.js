/* =====================================================================
   Snow White & the Seven Million Followers — show page
   Drives the scroll-linked RealiTea logo, builds the production-photo filmstrip
   from window.SNOWWHITE_PHOTOS (images/snowwhite/show.js), then reads
   window.SNOWWHITE_PEOPLE (images/snowwhite/people.js) and fills each .people
   grid whose data-group matches. Both data files are generated by
   build-snowwhite.sh.
   Each person is one full-width row: headshot with name + role beneath | bio.
   ===================================================================== */
(function () {
  "use strict";

  // ---- RealiTea logo: fade in at the synopsis, get creepier toward the end ----
  const logo = document.getElementById("realitea");
  const synopsis = document.getElementById("synopsis");
  if (logo && synopsis) {
    const frames = Array.from(logo.querySelectorAll("img"));
    // scroll progress at which each later variant takes over (0 = synopsis reached, 1 = page bottom)
    const cues = [0.18, 0.36, 0.54, 0.72, 0.9];
    // page geometry is measured on load/resize only, so scrolling never forces layout
    let start = 0, end = 1, stage = -1, ticking = false;
    const measure = () => {
      const vh = window.innerHeight;
      const synTop = synopsis.getBoundingClientRect().top + window.scrollY;
      start = synTop - vh * 0.4;                       // synopsis is entering the viewport
      end = document.documentElement.scrollHeight - vh; // as far down as the page goes
    };
    const update = () => {
      ticking = false;
      const p = Math.min(1, Math.max(0, (window.scrollY - start) / Math.max(1, end - start)));
      logo.classList.toggle("is-visible", window.scrollY >= start);
      const next = Math.min(frames.length - 1, cues.filter((c) => p >= c).length);
      if (next !== stage) {
        stage = next;
        frames.forEach((img, i) => img.classList.toggle("is-on", i === stage));
      }
    };
    const onScroll = () => { if (!ticking) { ticking = true; requestAnimationFrame(update); } };
    window.addEventListener("scroll", onScroll, { passive: true });
    window.addEventListener("resize", () => { measure(); onScroll(); });
    window.addEventListener("load", () => { measure(); update(); });
    measure(); update();

    // touch screens have no hover: a tap dissolves the logo into the pitch,
    // which lingers a few seconds and then fades back on its own. Another tap
    // restarts the clock. Mouse users get hover only.
    const framesEl = logo.querySelector(".realitea__frames");
    if (framesEl && window.matchMedia("(hover: none)").matches) {
      let timer = 0;
      framesEl.addEventListener("click", () => {
        logo.classList.add("is-pitch");
        clearTimeout(timer);
        timer = setTimeout(() => logo.classList.remove("is-pitch"), 2000);
      });
    }
    // a lifted finger also "leaves", so only a mouse moving away clears the pitch
    logo.addEventListener("pointerleave", (e) => { if (e.pointerType === "mouse") logo.classList.remove("is-pitch"); });

    // the ad's close button: "Are you sure?" — and the only answer is No
    const nope = document.getElementById("nope");
    const close = document.getElementById("realiteaClose");
    const no = document.getElementById("nopeNo");
    if (nope && close && no) {
      close.addEventListener("click", () => { nope.hidden = false; no.focus(); });
      no.addEventListener("click", () => { nope.hidden = true; close.focus(); });
      document.addEventListener("keydown", (e) => { if (e.key === "Escape" && !nope.hidden) { nope.hidden = true; } });
    }
  }

  // ---- production photos: the run across a few filmstrips, click for full size ----
  const strips = document.getElementById("photoStrips");
  const shots = Array.isArray(window.SNOWWHITE_PHOTOS) ? window.SNOWWHITE_PHOTOS : [];
  if (strips && shots.length) {
    const credit = strips.dataset.credit || "";
    const rows = Math.max(1, parseInt(strips.dataset.rows, 10) || 1);
    const base = "images/snowwhite/show/";
    const label = (i) => i + 1 + " / " + shots.length + (credit ? " · Photo by " + credit : "");
    const alt = (i) => "Production photo " + (i + 1) + " from Snow White & the Seven Million Followers";

    // each tile carries its master's aspect ratio, so a row's full width is
    // known before a single thumbnail has loaded and nothing shifts as they do
    const tile = (p, i) =>
      '<figure class="shot" data-i="' + i + '" tabindex="0" role="button" style="aspect-ratio:' +
      p.w + "/" + p.h + '" aria-label="Open production photo ' + (i + 1) + ' of ' + shots.length +
      '"><img src="' + base + "thumbs/" + p.id + '.webp" alt="' + alt(i).replace(/&/g, "&amp;") +
      '" loading="lazy" decoding="async"></figure>';

    // the run split into equal rows, still in order. data-i stays the index into
    // the whole set, so the lightbox arrows carry on across a row's edge.
    const per = Math.ceil(shots.length / rows);
    let html = "";
    for (let r = 0; r < rows; r++) {
      const from = r * per;
      const slice = shots.slice(from, from + per);
      if (!slice.length) break;
      html +=
        '<div class="filmstrip">' +
          '<div class="filmstrip__rail">' + slice.map((p, k) => tile(p, from + k)).join("") + "</div>" +
          '<button class="filmstrip__nav filmstrip__nav--prev" type="button" aria-label="Scroll row ' +
            (r + 1) + ' left">&lsaquo;</button>' +
          '<button class="filmstrip__nav filmstrip__nav--next" type="button" aria-label="Scroll row ' +
            (r + 1) + ' right">&rsaquo;</button>' +
        "</div>";
    }
    strips.innerHTML = html;

    const lb = document.createElement("div");
    lb.className = "lightbox";
    lb.innerHTML =
      '<button class="lightbox__close" aria-label="Close">&times;</button>' +
      '<button class="lightbox__nav lightbox__prev" aria-label="Previous">&lsaquo;</button>' +
      '<img class="lightbox__img" alt="">' +
      '<button class="lightbox__nav lightbox__next" aria-label="Next">&rsaquo;</button>' +
      '<div class="lightbox__caption"></div>';
    document.body.appendChild(lb);
    const lbImg = lb.querySelector(".lightbox__img");
    const lbCap = lb.querySelector(".lightbox__caption");
    let idx = 0;

    const show = (i) => {
      idx = (i + shots.length) % shots.length;
      lbImg.src = base + "web/" + shots[idx].id + ".webp";   // full size loads only when opened
      lbImg.alt = alt(idx);
      lbCap.textContent = label(idx);
      // warm the neighbours so arrowing through the run doesn't flash
      [idx + 1, idx - 1].forEach((n) => {
        const p = shots[(n + shots.length) % shots.length];
        new Image().src = base + "web/" + p.id + ".webp";
      });
    };
    const close = () => {
      lb.classList.remove("is-open");
      document.body.style.overflow = "";
      lbImg.removeAttribute("src");
    };
    lb.querySelector(".lightbox__close").addEventListener("click", close);
    lb.querySelector(".lightbox__prev").addEventListener("click", (e) => { e.stopPropagation(); show(idx - 1); });
    lb.querySelector(".lightbox__next").addEventListener("click", (e) => { e.stopPropagation(); show(idx + 1); });
    lb.addEventListener("click", (e) => { if (e.target === lb) close(); });
    document.addEventListener("keydown", (e) => {
      if (!lb.classList.contains("is-open")) return;
      if (e.key === "Escape") close();
      else if (e.key === "ArrowLeft") show(idx - 1);
      else if (e.key === "ArrowRight") show(idx + 1);
    });

    strips.querySelectorAll(".shot").forEach((fig) => {
      const open = () => {
        show(parseInt(fig.dataset.i, 10));
        lb.classList.add("is-open");
        document.body.style.overflow = "hidden";
      };
      fig.addEventListener("click", open);
      fig.addEventListener("keydown", (e) => {
        if (e.key === "Enter" || e.key === " ") { e.preventDefault(); open(); }
      });
    });

    // every row scrolls on its own, by arrow or by swipe. Each press moves most
    // of a screenful, and the arrow at whichever end that row has reached hides.
    const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    strips.querySelectorAll(".filmstrip").forEach((row) => {
      const rail = row.querySelector(".filmstrip__rail");
      const prev = row.querySelector(".filmstrip__nav--prev");
      const next = row.querySelector(".filmstrip__nav--next");
      const ends = () => {
        const max = rail.scrollWidth - rail.clientWidth;
        prev.hidden = rail.scrollLeft <= 4;
        next.hidden = rail.scrollLeft >= max - 4;
      };
      // behavior is passed here rather than set in CSS: a rail-level
      // scroll-behavior would sit after the reduced-motion block in the
      // stylesheet and win over it, so a reader who asked for less motion
      // would get the animation anyway.
      const page = (dir) =>
        rail.scrollBy({
          left: dir * rail.clientWidth * 0.9,
          behavior: reduceMotion ? "auto" : "smooth"
        });
      prev.addEventListener("click", () => page(-1));
      next.addEventListener("click", () => page(1));
      let pending = false;
      rail.addEventListener("scroll", () => {
        if (pending) return;
        pending = true;
        requestAnimationFrame(() => { pending = false; ends(); });
      }, { passive: true });
      window.addEventListener("resize", ends);
      ends();
    });
  }

  const groups = Array.isArray(window.SNOWWHITE_PEOPLE) ? window.SNOWWHITE_PEOPLE : [];
  const grids = document.querySelectorAll(".people[data-group]");
  if (!groups.length || !grids.length) return;

  const esc = (s) =>
    String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

  // Escape first, then turn full URLs, bare domains and @handles into links,
  // in one pass so a link's own href never gets re-matched. Trailing sentence
  // punctuation ("site.com.", "@handle,") stays outside the link.
  const link = (href, text) =>
    '<a href="' + href + '" target="_blank" rel="noopener">' + text + "</a>";
  const linkify = (text) =>
    esc(text).replace(
      /(^|[\s(|])(?:(https?:\/\/[^\s<>()|]+?)|@([A-Za-z0-9_.]+?)|((?:[A-Za-z0-9-]+\.)+(?:com|org|net|io|co)(?:\/[^\s<>()|]*?)?))([.,;!?]*)(?=[\s)|]|$)/g,
      (m, pre, url, handle, domain, punct) =>
        pre +
        (url ? link(url, url) : handle ? link("https://instagram.com/" + handle, "@" + handle) : link("https://" + domain, domain)) +
        punct
    );
  // *Title* in the bios file -> italics (show titles). Runs after linkify, so
  // the asterisks never end up inside an href.
  const emphasize = (html) => html.replace(/\*([^*]+)\*/g, "<em>$1</em>");

  const initials = (name) =>
    name.split(/\s+/).filter(Boolean).slice(0, 2).map((w) => w[0].toUpperCase()).join("");

  const card = (p) => {
    // optional "x% y%" focal point from the bios file, for off-center photos
    const focus = /^\d{1,3}% \d{1,3}%$/.test(p.focus || "") ? ' style="object-position:' + p.focus + '"' : "";
    const photo = p.image
      ? '<img src="' + esc(p.image) + '" alt="Headshot of ' + esc(p.name) + '" loading="lazy" decoding="async"' + focus + ">"
      : '<span class="person__initials" aria-hidden="true">' + esc(initials(p.name)) + "</span>";
    const bio = (p.bio || []).filter((t) => t.trim());
    return (
      '<article class="person reveal">' +
        '<div class="person__id">' +
          '<div class="person__photo">' + photo + "</div>" +
          '<h3 class="person__name">' + esc(p.name) + "</h3>" +
          (p.role ? '<p class="person__role">' + esc(p.role) + "</p>" : "") +
        "</div>" +
        '<div class="person__bio">' + bio.map((t) => "<p>" + emphasize(linkify(t)) + "</p>").join("") + "</div>" +
      "</article>"
    );
  };

  grids.forEach((grid) => {
    const group = groups.find((g) => g.name.toLowerCase() === grid.dataset.group.toLowerCase());
    const people = group ? group.people : [];
    if (!people.length) {
      grid.innerHTML = '<p class="people__empty">To be announced.</p>';
      return;
    }
    grid.innerHTML = people.map(card).join("");

    // a missing derivative degrades to the initials placeholder, not a broken image
    grid.querySelectorAll(".person__photo img").forEach((img) => {
      img.addEventListener("error", () => {
        const name = img.closest(".person").querySelector(".person__name").textContent;
        img.replaceWith(Object.assign(document.createElement("span"), {
          className: "person__initials", textContent: initials(name)
        }));
      });
    });

    // cards were added after main.js set up its observer, so reveal them here
    const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    const cards = grid.querySelectorAll(".reveal");
    if ("IntersectionObserver" in window && !reduceMotion) {
      const io = new IntersectionObserver((entries) => {
        entries.forEach((e) => {
          if (e.isIntersecting) { e.target.classList.add("in-view"); io.unobserve(e.target); }
        });
      }, { threshold: 0.12, rootMargin: "0px 0px -8% 0px" });
      cards.forEach((el) => io.observe(el));
    } else {
      cards.forEach((el) => el.classList.add("in-view"));
    }
  });
})();
